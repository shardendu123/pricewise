export function getProductById(id: string): Product | undefined {
  return sampleProducts.find((p) => p.id === id);
}

export function getProductsByCategory(category: Product['category']): Product[] {
  return sampleProducts.filter((p) => p.category === category);
}

export function getTopRated(count = 4): Product[] {
  return [...sampleProducts].sort((a, b) => b.rating - a.rating).slice(0, count);
}

export function getTrendingProducts(count = 6): Product[] {
  return [...sampleProducts].sort((a, b) => b.reviewCount - a.reviewCount).slice(0, count);
}

